// Two filaments on two cubes with a prime tower, so the plate has model, flush and tower material.
DynamicPrintConfig priced_two_filaments()
{
    DynamicPrintConfig config = DynamicPrintConfig::full_print_config();
    config.set_num_extruders(2);
    config.set_num_filaments(2);
    config.option<ConfigOptionFloats>("filament_diameter")->values = { 1.75, 1.75 };
    config.option<ConfigOptionFloats>("nozzle_diameter")->values   = { 0.4, 0.4 };
    config.option<ConfigOptionStrings>("filament_colour")->values  = { "#FF0000", "#0000FF" };
    config.option<ConfigOptionFloats>("filament_density")->values  = { 1.24, 1.27 };
    config.option<ConfigOptionFloats>("filament_cost")->values     = { 25., 31.5 };
    config.option<ConfigOptionFloat>("time_cost")->value           = 1.5;
    config.option<ConfigOptionBool>("enable_prime_tower")->value   = true;
    config.option<ConfigOptionBool>("enable_support")->value       = false;
    config.option<ConfigOptionFloats>("wipe_tower_x")->values      = { 15. };
    config.option<ConfigOptionFloats>("wipe_tower_y")->values      = { 15. };
    config.option<ConfigOptionFloat>("prime_tower_width")->value   = 35.;
    config.set_deserialize_strict({ { "brim_type", "no_brim" }, { "skirt_loops", "0" }, { "wipe_tower_wall_type", "rectangle" },
                                    { "sparse_infill_density", "10%" } });
    return config;
}

void two_cubes(Model &model)
{
    ModelObject *first = model.add_object();
    first->name        = "cube-a.stl";
    first->add_volume(mesh(TestMesh::cube_20x20x20));
    first->add_instance()->set_offset(Vec3d(80., 40., 0.));
    first->ensure_on_bed();
    ModelObject *second = model.add_object();
    second->name        = "cube-b.stl";
    second->add_volume(mesh(TestMesh::cube_20x20x20));
    second->add_instance()->set_offset(Vec3d(120., 40., 0.));
    second->ensure_on_bed();
    second->volumes.front()->config.set("extruder", 2);
}

std::string read_file(const std::string &path)
{
    std::ifstream t(path, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(t)), std::istreambuf_iterator<char>());
}

// Slice + export into `path`, keeping the processor result.
std::string export_to(Print &print, const std::string &path, GCodeProcessorResult *result)
{
    print.set_status_silent();
    print.process();
    print.export_gcode(path, result, nullptr);
    return read_file(path);
}

std::string slice_plate(bool bbl, bool prices, GCodeProcessorResult *result = nullptr)
{
    Print print;
    Model model;
    two_cubes(model);
    print.apply(model, priced_two_filaments());
    print.is_BBL_printer() = bbl;
    print.set_gcode_filament_prices(prices);
    const boost::filesystem::path path = scratch_path();
    std::string gcode = export_to(print, path.string(), result);
    boost::nowide::remove(path.string().c_str());
    return gcode;
}

bool is_price_line(const std::string &line)
{
    return line.rfind("; filament cost =", 0) == 0 || line.rfind("; total filament cost =", 0) == 0 ||
           line.rfind("; filament_cost =", 0) == 0;
}

// Drops what differs between two slices of the same plate in one process (header timestamp, object
// label ids, which keep counting across Models) and, when asked, the price lines.
std::string normalized(const std::string &gcode, bool drop_prices)
{
    std::istringstream in(gcode);
    std::ostringstream out;
    std::string        line;
    while (std::getline(in, line)) {
        if (line.find("generated by") != std::string::npos || line.find("label id") != std::string::npos)
            continue;
        if (drop_prices && is_price_line(line))
            continue;
        out << line << '\n';
    }
    return out.str();
}

size_t count_price_lines(const std::string &gcode)
{
    std::istringstream in(gcode);
    std::string        line;
    size_t             n = 0;
    while (std::getline(in, line))
        n += is_price_line(line);
    return n;
}

std::string first_difference(const std::string &a, const std::string &b)
{
    std::istringstream ia(a), ib(b);
    std::string        la, lb;
    for (int n = 1;; ++n) {
        const bool ga = bool(std::getline(ia, la)), gb = bool(std::getline(ib, lb));
        if (!ga && !gb)
            return "identical";
        if (!ga || !gb || la != lb)
            return "line " + std::to_string(n) + ":\n  " + (ga ? la : "<eof>") + "\n  " + (gb ? lb : "<eof>");
    }
}

