/**
 * @file SentryWrapper.cpp
 * @brief Opt-in crash reporting (sentry-native + crashpad).
 *
 * What EdgeSlicer does with Sentry, all of it here:
 *   - crashpad always runs and keeps local minidumps (%LOCALAPPDATA%\EdgeSlicer\reports on
 *     Windows) - that is what we debug with, and it sends nothing by itself;
 *   - a crash report is uploaded only when BOTH
 *       (a) this build has a destination: the DSN CI compiles in from the SENTRY_DSN secret
 *           (EDGESLICER_SENTRY_DSN, see CMakeLists.txt), or a tester's "ultra_sentry_dsn" in
 *           the app config, which wins when set; local builds have neither, and
 *       (b) the user switched on Preferences > General > Privacy > "Send crash reports"
 *           (app config "send_crash_reports", default off), enforced through Sentry's own
 *           consent switch so it gates crashpad's uploads as well;
 *   - a report holds the minidump (thread stacks, registers, loaded modules), the app
 *     version as the release, the OS (Sentry's own context) and the most recent warning /
 *     error log lines as breadcrumbs (crashpad keeps two rotating files of 50, so at most
 *     100), each passed through scrub_for_crash_report() before it is stored. No log
 *     files, configs, projects, user id, machine id or host name;
 *   - no usage events, "bury point" logs, sessions or traces are ever sent.
 *
 * When SLIC3R_SENTRY is not defined every function is a no-op.
 */

